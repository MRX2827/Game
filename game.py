def detector_led(world, now_s):
    """Огонёк детектора: без улучшения дежурно мигает, с «Датчиком зомби» учащается рядом с зомби."""
    if not world.done[2]:
        return (70, 200, 100) if (now_s * 0.5) % 1.0 < 0.15 else None
    dmin = min((math.hypot(z.x - world.px, z.y - world.py) for z in world.zombies
                if z.retreat is None and z.burn <= 0), default=1e9)
    if dmin < 4 * TILE:
        rate, col = 6.0, (255, 60, 50)
    elif dmin < 8 * TILE:
        rate, col = 3.5, (255, 90, 50)
    elif dmin < 14 * TILE:
        rate, col = 1.8, (255, 170, 40)
    else:
        rate, col = 0.7, (80, 255, 120)
    return col if (now_s * rate) % 1.0 < 0.5 else None


def draw_stalker(screen, world, images, sprites, pxs, pys, now_s):
    """Сталкер: 4 направления, ходьба из 4 кадров, дыхание в покое, огни детектора и фонаря."""
    if "player" in images:
        screen.blit(images["player"], (pxs - TILE // 2, pys - TILE // 2))
        return
    if world.hurt_cd > 0 and int(now_s * 14) % 2 == 0:
        return                                       # мигает, пока ему больно
    state = "walk" if world.moving else "idle"
    frame = int(world.walk_phase) % 4 if world.moving else int(now_s * 1.6) % 2
    img = sprites["player"][world.facing][state][frame]
    meta = sprites["player_meta"][world.facing][state][frame]
    bx, by = pxs - img.get_width() // 2, pys + 20 - FEET * PX
    screen.blit(img, (bx, by))
    col = detector_led(world, now_s)
    if col and meta.get("led"):
        lx, ly = meta["led"]
        pygame.draw.rect(screen, col, (bx + lx * PX, by + ly * PX, PX, PX))
    if world.done[0] and meta.get("lamp"):
        lx, ly, lw = meta["lamp"]
        pygame.draw.rect(screen, (255, 248, 190), (bx + lx * PX, by + ly * PX, lw * PX, PX))


