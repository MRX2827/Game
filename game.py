class Editor:
    def __init__(self, rect, font):
        self.rect = rect
        self.font = font
        self.lh = font.get_linesize() + 2
        self.set_text(STARTER)

    def set_text(self, text):
        self.lines = text.split("\n")
        self.error_line = None
        self.row = len(self.lines) - 1
        self.col = len(self.lines[self.row])
        self.top = 0

    def text(self):
        return "\n".join(self.lines)

    def insert(self, s):
        self.error_line = None
        line = self.lines[self.row]
        self.lines[self.row] = line[:self.col] + s + line[self.col:]
        self.col += len(s)

    def paste(self, text):
        self.error_line = None
        text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
        if not text:
            return
        parts = text.split("\n")
        line = self.lines[self.row]
        before, after = line[:self.col], line[self.col:]
        if len(parts) == 1:
            self.lines[self.row] = before + parts[0] + after
            self.col += len(parts[0])
            return
        new_lines = [before + parts[0]] + parts[1:-1] + [parts[-1] + after]
        self.lines[self.row:self.row + 1] = new_lines
        self.row += len(parts) - 1
        self.col = len(parts[-1])

    def newline(self):
        self.error_line = None
        line = self.lines[self.row]
        before, after = line[:self.col], line[self.col:]
        indent = len(before) - len(before.lstrip(" "))
        if before.rstrip().endswith(":"):
            indent += 4
        self.lines[self.row] = before
        self.lines.insert(self.row + 1, " " * indent + after)
        self.row += 1
        self.col = indent

    def backspace(self):
        self.error_line = None
        if self.col > 0:
            line = self.lines[self.row]
            self.lines[self.row] = line[:self.col - 1] + line[self.col:]
            self.col -= 1
        elif self.row > 0:
            prev = self.lines[self.row - 1]
            self.col = len(prev)
            self.lines[self.row - 1] = prev + self.lines[self.row]
            del self.lines[self.row]
            self.row -= 1

    def delete_forward(self):
        self.error_line = None
        line = self.lines[self.row]
        if self.col < len(line):
            self.lines[self.row] = line[:self.col] + line[self.col + 1:]
        elif self.row < len(self.lines) - 1:
            self.lines[self.row] = line + self.lines[self.row + 1]
            del self.lines[self.row + 1]

    def click(self, pos):
        """Поставить курсор туда, куда кликнули мышью."""
        row = self.top + (pos[1] - self.rect.y - 8) // self.lh
        self.row = max(0, min(int(row), len(self.lines) - 1))
        line = self.lines[self.row]
        target = pos[0] - (self.rect.x + 42)
        best, best_diff = 0, 10 ** 9
        for c in range(len(line) + 1):
            diff = abs(self.font.size(line[:c])[0] - target)
            if diff < best_diff:
                best, best_diff = c, diff
        self.col = best

    def key(self, event):
        k = event.key
        cmd = event.mod & (pygame.KMOD_META | pygame.KMOD_CTRL)
        if k == pygame.K_RETURN:
            self.newline()
        elif k == pygame.K_BACKSPACE and cmd:
            self.error_line = None
            line = self.lines[self.row]
            self.lines[self.row] = line[self.col:]
            self.col = 0
        elif k == pygame.K_BACKSPACE:
            self.backspace()
        elif k == pygame.K_DELETE:
            self.delete_forward()
        elif k == pygame.K_HOME or (cmd and k == pygame.K_LEFT):
            self.col = 0
        elif k == pygame.K_END or (cmd and k == pygame.K_RIGHT):
            self.col = len(self.lines[self.row])
        elif k == pygame.K_TAB:
            self.insert("    ")
        elif k == pygame.K_LEFT:
            if self.col > 0:
                self.col -= 1
            elif self.row > 0:
                self.row -= 1
                self.col = len(self.lines[self.row])
        elif k == pygame.K_RIGHT:
            if self.col < len(self.lines[self.row]):
                self.col += 1
            elif self.row < len(self.lines) - 1:
                self.row += 1
                self.col = 0
        elif k == pygame.K_UP and self.row > 0:
            self.row -= 1
            self.col = min(self.col, len(self.lines[self.row]))
        elif k == pygame.K_DOWN and self.row < len(self.lines) - 1:
            self.row += 1
            self.col = min(self.col, len(self.lines[self.row]))

    def draw(self, screen, active):
        pygame.draw.rect(screen, CODE_BG, self.rect, border_radius=8)
        pygame.draw.rect(screen, GREEN if active else MUTED, self.rect, 2, border_radius=8)
        visible = (self.rect.height - 16) // self.lh
        if self.row < self.top:
            self.top = self.row
        if self.row >= self.top + visible:
            self.top = self.row - visible + 1
        clip = screen.get_clip()
        screen.set_clip(self.rect.inflate(-4, -4))
        for i in range(visible):
            n = self.top + i
            if n >= len(self.lines):
                break
            y = self.rect.y + 8 + i * self.lh
            num = self.font.render(str(n + 1), True, (90, 100, 95))
            screen.blit(num, (self.rect.x + 30 - num.get_width(), y))
            line = self.lines[n]
            if self.error_line == n + 1:
                pygame.draw.rect(screen, (85, 38, 38), (self.rect.x + 4, y - 1, self.rect.width - 8, self.lh))
            lead = len(line) - len(line.lstrip(" "))
            if lead and line.strip():
                cw = self.font.size(" ")[0]
                for k in range(lead):
                    pygame.draw.circle(screen, (110, 120, 115),
                                       (self.rect.x + 42 + k * cw + cw // 2, y + self.lh // 2), 2)
            color = (120, 140, 120) if line.strip().startswith("#") else TEXT
            screen.blit(self.font.render(line, True, color), (self.rect.x + 42, y))
            if n == self.row and active and (pygame.time.get_ticks() // 500) % 2 == 0:
                cx = self.rect.x + 42 + self.font.size(line[:self.col])[0]
                pygame.draw.line(screen, YELLOW, (cx, y), (cx, y + self.lh - 2), 2)
        screen.set_clip(clip)


