def build_overlays():
    """Рамка из листвы с лианами по углам, лучи света и лёгкая дымка."""
    def canopy(seed):
        rng = random.Random(seed)
        pal = GREENS[seed % 3]

        def fn(s):
            for i in range(0, 132, 6):
                blob(s, i + rng.randint(-2, 2), rng.randint(0, 5), rng.randint(5, 8), pal)
            for j in range(0, 62, 7):
                blob(s, rng.randint(0, 6), j + rng.randint(0, 4), rng.randint(4, 7), pal)
            dither(s, rng, 140, [HILITE, pal[0], pal[2]], (0, 0, 129, 62))
            for i in range(11):
                x, y0, length = rng.randint(6, 124), rng.randint(6, 13), rng.randint(14, 46)
                for k in range(length):
                    xx = x + int(math.sin(k * 0.35 + i) * 1.5)
                    if 0 <= xx < 130 and y0 + k < 70:
                        s.set_at((xx, y0 + k), pal[1] if k % 5 else HILITE)
                        if k % 6 == 4 and xx + 1 < 130:
                            s.set_at((xx + 1, y0 + k), pal[2])
        return pix(130, 70, fn)

    def rays_fn(s):
        for (x, w, slope) in ((40, 14, 60), (110, 22, 80), (190, 10, 50), (260, 18, 70), (330, 12, 55)):
            pygame.draw.polygon(s, (255, 244, 180, 40), [(x, 0), (x + w, 0), (x + w + slope, 234), (x + slope, 234)])
    haze = pygame.Surface((W, H))
    haze.fill((190, 226, 176))
    left = canopy(1)
    return {
        "canopyL": left.convert_alpha(),
        "canopyR": pygame.transform.flip(canopy(2), True, False).convert_alpha(),
        "rays": pix(374, 234, rays_fn).convert_alpha(),
        "haze": haze,
    }


def draw_overlays(screen, ov, k, day, rain, now_s):
    """k: насколько густой лес вокруг игрока (0..1); day: 1 днём, 0 ночью."""
    if k <= 0.02:
        return
    haze_a = int(30 * k * day)
    if haze_a > 0:
        ov["haze"].set_alpha(haze_a)
        screen.blit(ov["haze"], (0, 0))
    ray_a = int(255 * k * day * (1.0 - 0.8 * rain) * (0.7 + 0.3 * math.sin(now_s * 0.6)))
    if ray_a > 6:
        ov["rays"].set_alpha(max(0, min(255, ray_a)))
        screen.blit(ov["rays"], (0, 0))
    a = int(235 * k)
    ov["canopyL"].set_alpha(a)
    screen.blit(ov["canopyL"], (0, 0))
    ov["canopyR"].set_alpha(a)
    screen.blit(ov["canopyR"], (W - ov["canopyR"].get_width(), 0))


class Critters:
    """Днём в траве порхают бабочки, ночью светятся светлячки."""
    BUTTERFLY = [(250, 160, 40), (240, 90, 150), (120, 170, 250), (250, 230, 90)]

    def __init__(self):
        self.rng = random.Random(9)
        self.items = []     # [x, y, курс, скорость, фаза, вид (0 бабочка, 1 светлячок), цвет]

    def update(self, dt, cam_x, cam_y, n_butterflies, n_fireflies):
        r = self.rng
        keep = []
        for c in self.items:
            c[2] += r.uniform(-4, 4) * dt
            c[0] += math.cos(c[2]) * c[3] * dt
            c[1] += math.sin(c[2]) * c[3] * dt * 0.6
            if -300 < c[0] - cam_x < W + 300 and -300 < c[1] - cam_y < H + 300:
                keep.append(c)
        self.items = keep
        for kind, want in ((0, n_butterflies), (1, n_fireflies)):
            have = [c for c in self.items if c[5] == kind]
            if len(have) < want:
                self.items.append([cam_x + r.uniform(-100, W + 100), cam_y + r.uniform(-100, H + 100),
                                   r.uniform(0, 6.28), r.uniform(25, 55) if kind == 0 else r.uniform(8, 20),
                                   r.uniform(0, 6.28), kind, r.choice(self.BUTTERFLY)])
            elif len(have) > want:
                self.items.remove(have[0])

    def draw(self, screen, cam_x, cam_y, now_s, kind):
        for c in self.items:
            if c[5] != kind:
                continue
            sx = int(c[0] - cam_x)
            sy = int(c[1] - cam_y + math.sin(now_s * 3 + c[4]) * 4)
            if not (-20 < sx < W + 20 and -20 < sy < H + 20):
                continue
            if kind == 0:
                flap = abs(math.sin(now_s * 12 + c[4]))
                ww = (1 + int(flap * 2)) * PX
                pygame.draw.rect(screen, c[6], (sx - ww, sy - PX, ww, 2 * PX))
                pygame.draw.rect(screen, c[6], (sx + PX, sy - PX, ww, 2 * PX))
                pygame.draw.rect(screen, (40, 30, 30), (sx, sy - PX, PX, 2 * PX + 2))
            else:
                b = (math.sin(now_s * 2.2 + c[4]) + 1.0) / 2.0
                pygame.draw.circle(screen, (int(40 + 40 * b), int(60 + 60 * b), int(20 + 10 * b)), (sx, sy), 6)
                pygame.draw.circle(screen, (int(150 + 90 * b), int(190 + 50 * b), int(60 + 40 * b)), (sx, sy), 3)


