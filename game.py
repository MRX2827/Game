    x = np.concatenate([hoot(390, 0.2), np.zeros(_n(0.14)), hoot(390, 0.2), np.zeros(_n(0.1)), hoot(340, 0.6)])
    return _norm(_echo(_band(x, None, 900), 0.25, 0.3), 0.5)


