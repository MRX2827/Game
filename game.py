def _notes(seq, gap=0.03):
    parts = []
    for (f0, f1, d) in seq:
        n = _n(d)
        ph = 2 * np.pi * np.cumsum(np.linspace(f0, f1, n)) / SR
        y = (np.sin(ph) + 0.25 * np.sin(2 * ph)) * np.sin(np.pi * np.linspace(0, 1, n)) ** 0.7
        parts.append(y)
        parts.append(np.zeros(_n(gap)))
    return np.concatenate(parts)


