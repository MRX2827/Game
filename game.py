def describe_error(e):
    line = player_line(e.__traceback__)
    where = f"Строка {line}: " if line else ""
    if isinstance(e, GameError):
        body = str(e)
    elif isinstance(e, NameError):
        body = (f"Python не знает слова «{getattr(e, 'name', '?')}». Проверь опечатки: переменную нужно создать "
                f"до использования, а текст писать в кавычках.")
    elif isinstance(e, ZeroDivisionError):
        body = "Делить на ноль нельзя."
    elif isinstance(e, TypeError):
        body = f"Неверное использование команды или действие с несовместимыми типами. (Python пишет: {e})"
    else:
        body = f"{type(e).__name__}: {e}"
    return where + body


def exec_code(code, presets=None, inputs=None):
    """Выполняет код игрока в песочнице. Возвращает (окружение, строки вывода, ошибка или None)."""
    buf = []
    answers = list(inputs or [])

    def game_print(*args, sep=" ", end="\n"):
        buf.append(sep.join(str(a) for a in args) + end)

    def game_input(prompt=""):
        answer = answers.pop(0) if answers else ""
        buf.append(str(prompt) + str(answer) + "\n")
        return answer

    safe = {name: getattr(builtins, name) for name in _BASE_NAMES}
    safe["print"] = game_print
    safe["input"] = game_input
    env = {"__builtins__": safe}
    env.update(presets or {})
    try:
        compiled = compile(code, "<игрок>", "exec")
    except SyntaxError as e:
        return env, [], friendly_syntax(e)
    error = None
    try:
        sys.settrace(make_tracer())
        exec(compiled, env)
    except Exception as e:
        error = describe_error(e)
    finally:
        sys.settrace(None)
    lines = "".join(buf).split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return env, lines, error


def call_limited(fn, *args):
    try:
        sys.settrace(make_tracer())
        return fn(*args)
    finally:
        sys.settrace(None)


def check_rules(code, lesson):
    for bad in lesson.get("forbid", []):
        if bad in code:
            return f"На этом уроке нельзя использовать «{bad}»: напиши сам."
    for need in lesson.get("must_contain", []):
        if need not in code:
            return f"В твоём коде не хватает «{need}». Перечитай задание и теорию."
    options = lesson.get("must_any")
    if options and not any(x in code for x in options):
        return "В коде не хватает нужной конструкции. Посмотри пример в теории (кнопка «Теория»)."
    for word, n in lesson.get("must_count", {}).items():
        if code.count(word) < n:
            return f"Используй «{word}» в своём коде, а не пиши результат вручную."
    if lesson.get("need_comment") and not any(ln.strip().startswith("#") for ln in code.split("\n")):
        return "Нужен комментарий: строка, которая начинается со знака #."
    return None


def run_console(code, lesson):
    """Проверяет консольный урок. Возвращает (успех, строки для экрана, сообщение)."""
    tests = lesson.get("tests") or [({}, None)]
    env, shown, err = exec_code(code, tests[0][0])
    if err:
        return False, shown, err
    msg = check_rules(code, lesson)
    if msg:
        return False, shown, msg
    for i, (presets, expected) in enumerate(tests):
        if i == 0:
            out = shown
        else:
            _, out, err = exec_code(code, presets)
            if err:
                return False, shown, err
        if expected is not None and out != expected:
            label = ", ".join(f"{k} = {v}" for k, v in presets.items())
            got = " / ".join(out) if out else "ничего не выведено"
            where = f" при {label}" if label else ""
            return False, shown, (f"Пока не сходится{where}: у тебя вывелось «{got}», "
                                  f"а нужно «{' / '.join(expected)}».")
    for (name, args, expected) in lesson.get("func_tests", []):
        fn = env.get(name)
        if not callable(fn):
            return False, shown, (f"Не нашёл функцию {name}. Проверь, что описал её через def "
                                  f"и что имя написано точно так же.")
        try:
            result = call_limited(fn, *args)
        except Exception as e:
            return False, shown, f"Функция {name} упала с ошибкой. {describe_error(e)}"
        if result != expected:
            shown_args = ", ".join(repr(x) for x in args)
            return False, shown, f"{name}({shown_args}) вернула {result!r}, а нужно {expected!r}. Проверь return."
    for var, value in lesson.get("expect_vars", {}).items():
        if env.get(var) != value:
            return False, shown, f"Переменная {var} должна быть равна {value!r}, а сейчас {env.get(var)!r}."
    return True, shown, lesson.get("win", "Верно!")


