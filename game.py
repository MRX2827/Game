    x = _band(_white(0.5, 301), 150, 1200) * (0.6 + 0.4 * np.sin(2 * np.pi * 28 * t))
    x = x + 0.5 * np.sin(2 * np.pi * 95 * t) * (0.6 + 0.4 * np.sin(2 * np.pi * 28 * t))
    return _norm(x * np.sin(np.pi * t / 0.5) ** 0.6, 0.65)


