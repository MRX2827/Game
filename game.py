            for x in range(MAP_W):
                if x < 2 or y < 2 or x >= MAP_W - 2 or y >= MAP_H - 2:
                    t = T_TREE
                elif bx1 <= x <= bx2 and by1 <= y <= by2:
                    edge = x in (bx1, bx2) or y in (by1, by2)
                    t = T_FENCE if edge else T_FLOOR
                elif ((x - lcx) / lrx) ** 2 + ((y - lcy) / lry) ** 2 < 1:
                    t = T_WATER
                else:
                    n = forest_noise(x, y)
                    jungle, meadow = n > 1.2, n < -0.3
                    self.zone[y][x] = 1 if jungle else (2 if meadow else 0)
                    tree_p = 0.22 if jungle else (0.03 if meadow else 0.11)
                    bush_p = 0.07 if jungle else (0.03 if meadow else 0.06)
                    r = rng.random()
