def draw_zombie(screen, world, z, images, sprites, zx, zy, now_s):
    """Зомби: 4 облика, шаркающая походка, покачивание в покое, руки вверх при атаке."""
    if "zombie" in images:
        screen.blit(images["zombie"], (zx - TILE // 2, zy - TILE // 2))
        return
    dx, dy = world.px - z.x, world.py - z.y
    d = math.hypot(dx, dy)
    facing = z.facing
    if z.burn > 0:
        state, frame = "attack", int(now_s * 8) % 2          # горящий машет руками
    elif d < 1.5 * TILE and z.retreat is None:
        state, frame = "attack", int(now_s * 5) % 2          # тянется к игроку
        facing = ("right" if dx > 0 else "left") if abs(dx) > abs(dy) else ("down" if dy > 0 else "up")
    elif z.moving:
        state, frame = "walk", int(z.walk_phase) % 4
    else:
        state, frame = "idle", int(now_s * 1.4 + z.walk_phase) % 2
    img = sprites["zombies"][z.skin][facing][state][frame]
    screen.blit(img, (zx - img.get_width() // 2, zy + 19 - FEET * PX))


def draw_game_world(screen, world, images, sprites, ui, big, now_s):
    cam_x = int(max(0, min(world.px - W / 2, MAP_W * TILE - W)))
    cam_y = int(max(0, min(world.py - H / 2, MAP_H * TILE - H)))
    x0, y0 = cam_x // TILE, cam_y // TILE
    x1, y1 = min(MAP_W, x0 + W // TILE + 2), min(MAP_H, y0 + H // TILE + 2)

    # 1) земля: трава (тёмная в джунглях, светлая на полянах), тропинки, пол базы, вода
    for ty in range(y0, y1):
        for tx in range(x0, x1):
            t = world.tiles[ty][tx]
            sx, sy = tx * TILE - cam_x, ty * TILE - cam_y
            hsh = tile_hash(tx, ty)
            if t == T_WATER:
                img = images["water"] if "water" in images else sprites["water"][(int(now_s * 1.6) + hsh) % 4]
            elif inside_base(tx, ty):
                img = images["floor"] if "floor" in images else sprites["floor"][0 if hsh % 20 < 13 else 1 + hsh % 3]
            elif (tx, ty) in world.path:
                img = images["path"] if "path" in images else sprites["path"][hsh % 3]
            elif "grass" in images:
                img = images["grass"]
            else:
                zone = world.zone[ty][tx]
                img = sprites["grassd" if zone == 1 else ("grassl" if zone == 2 else "grass")][hsh % 8]
            screen.blit(img, (sx, sy))
            kind = world.decor.get((tx, ty))
            if kind in FLAT_DECOR:
                draw_decor_sprite(screen, sprites, kind, sx, sy, hsh, now_s)

    # 2) палки на земле
    for (sx_t, sy_t) in world.sticks:
        if x0 <= sx_t < x1 and y0 <= sy_t < y1:
            px, py = sx_t * TILE - cam_x, sy_t * TILE - cam_y
            if "stick" in images:
                screen.blit(images["stick"], (px, py))
            else:
                pygame.draw.line(screen, (150, 104, 56), (px + 14, py + TILE - 14), (px + TILE - 14, py + 14), 6)
                pygame.draw.line(screen, (190, 140, 80), (px + 14, py + TILE - 14), (px + TILE - 14, py + 14), 3)
                pygame.draw.line(screen, (110, 72, 40), (px + 22, py + 34), (px + 32, py + 40), 3)

    # 3) объекты, существа и трава по рядам сверху вниз: игрок заходит за деревья
    rows = {}
    for z in world.zombies:
        rows.setdefault(int((z.y + 14) // TILE), []).append(z)
    player_row = int((world.py + 16) // TILE)
    lit = world.fuel > 0
    for ty in range(y0, min(MAP_H, y1 + 2)):
        for tx in range(x0, x1):
            t = world.tiles[ty][tx]
            if t not in OBJECT_TILES:
                continue
            sx, sy = tx * TILE - cam_x, ty * TILE - cam_y
            hsh = tile_hash(tx, ty)
            key = {T_TREE: "tree", T_BUSH: "bush", T_ROCK: "rock", T_STUMP: "stump",
                   T_LOG: "log", T_FENCE: "fence"}.get(t)
            if key:
                lst = sprites[key]
                spr = images[key] if key in images else lst[hsh % len(lst)]
                screen.blit(spr, (sx - (spr.get_width() - TILE) // 2, sy + TILE - spr.get_height()))
                if t == T_TREE and (tx, ty) in world.vines:
                    frame = ANIM[int(now_s * 2.2 + hsh % 5) % 4]
                    screen.blit(sprites["vines"][hsh % 3][frame], (sx + (hsh % 5) - 2, sy + 2))
            elif t == T_FIRE:
                if "campfire" in images:
                    screen.blit(images["campfire"], (sx, sy))
                else:
                    screen.blit(sprites["fire"][int(now_s * 8) % 3] if lit else sprites["fire"][3], (sx, sy))
            elif t == T_TERM:
                draw_terminal(screen, world, tx, ty, sx, sy, images, ui)
        for tx in range(x0, x1):
            kind = world.decor.get((tx, ty))
            if kind in TALL_DECOR:
                draw_decor_sprite(screen, sprites, kind, tx * TILE - cam_x, ty * TILE - cam_y,
                                  tile_hash(tx, ty), now_s)
        for z in rows.get(ty, ()):
            zx, zy = int(z.x) - cam_x, int(z.y) - cam_y
            draw_zombie(screen, world, z, images, sprites, zx, zy, now_s)
            if z.burn > 0:                           # горит на утреннем солнце
                f = math.sin(now_s * 20 + z.x) * 3
                pygame.draw.polygon(screen, (232, 108, 36), [(zx - 10, zy + 10), (zx + f, zy - 36), (zx + 10, zy + 10)])
                pygame.draw.polygon(screen, (250, 200, 70), [(zx - 5, zy + 10), (zx - f / 2, zy - 20), (zx + 5, zy + 10)])
        if ty == player_row:
            pxs, pys = int(world.px) - cam_x, int(world.py) - cam_y
            draw_stalker(screen, world, images, sprites, pxs, pys, now_s)
            draw_puffs(screen, world, cam_x, cam_y)
        if ty < y1:
            for tx in range(x0, x1):
                kind = world.decor.get((tx, ty))
                if kind and kind not in FLAT_DECOR and kind not in TALL_DECOR:
                    draw_decor_sprite(screen, sprites, kind, tx * TILE - cam_x, ty * TILE - cam_y,
                                      tile_hash(tx, ty), now_s)
    for (x, y, age, drift) in world.smoke:                  # дым над сгоревшими зомби
        f = age / 1.3
        size = int(6 + f * 12)
        shade_c = int(170 - f * 60)
        pygame.draw.rect(screen, (shade_c, shade_c, shade_c + 6),
                         (int(x - cam_x + drift * age) - size // 2, int(y - cam_y - age * 40) - size // 2, size, size))
    return cam_x, cam_y


class Rain:
    """Дождь в стиле Terraria: косые струи двух слоёв и брызги на земле."""
    N = 340
    SLANT = 0.28

    def __init__(self):
        self.rng = random.Random(3)
        self.drops = [self._new(True) for _ in range(self.N)]
        self.splashes = []

    def _new(self, first=False):
        r = self.rng
        far = r.random() < 0.6
        speed = (520 if far else 840) * r.uniform(0.9, 1.1)
        y = r.uniform(-H, H) if first else r.uniform(-40, 0)
        return [r.uniform(-80, W), y, speed, 9 if far else 18, far, r.uniform(H * 0.25, H)]

    def update(self, dt, intensity, cam_dx=0.0, cam_dy=0.0):
        """Капли и брызги сдвигаются вместе с камерой: ближние как земля, дальние медленнее."""
        n = int(self.N * intensity)
        for d in self.drops[:n]:
            k = 0.55 if d[4] else 1.0
            d[0] += d[2] * self.SLANT * dt - cam_dx * k
            d[1] += d[2] * dt - cam_dy * k
            d[5] -= cam_dy * k
            if d[0] < -100:
                d[0] += W + 200
            elif d[0] > W + 100:
                d[0] -= W + 200
            landed = d[1] >= d[5]
            if landed or d[5] < -20 or d[5] > H + 80:
                if landed and not d[4] and 0 <= d[0] <= W and 0 <= d[5] <= H and len(self.splashes) < 90:
                    self.splashes.append([d[0], d[5], 0.0])
                d[:] = self._new()
        for sp in self.splashes:
            sp[2] += dt
            sp[0] -= cam_dx
            sp[1] -= cam_dy
        self.splashes = [sp for sp in self.splashes if sp[2] < 0.22]

    def draw(self, screen, intensity):
        n = int(self.N * intensity)
        for d in self.drops[:n]:
            x, y, ln, far = d[0], d[1], d[3], d[4]
            color = (112, 142, 196) if far else (178, 208, 250)
            pygame.draw.line(screen, color, (int(x), int(y)), (int(x + ln * self.SLANT), int(y + ln)), 1)
        for x, y, age in self.splashes:
            r = 2 + age * 45
            pygame.draw.ellipse(screen, (190, 214, 242),
                                (int(x - r), int(y - r * 0.4), int(2 * r), max(2, int(0.8 * r))), 1)


