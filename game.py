def make_vines(v, frame):
    rng = random.Random(v * 31 + 7)
    strands = [(rng.randint(1, 18), rng.randint(12, 23)) for _ in range(5)]
    sway = (-1, 0, 1)[frame]

    def fn(s):
        for i, (x0, length) in enumerate(strands):
            for k in range(length):
                xx = x0 + int(round(math.sin(k * 0.4 + i) * 1.2 + sway * k / 12.0))
                if 0 <= xx < SM:
                    s.set_at((xx, k), (24, 78, 44))
                    if k % 2 == 0 and xx + 1 < SM:
                        s.set_at((xx + 1, k), (40, 108, 56))
                    if k % 4 == 3 and xx - 1 >= 0:
                        s.set_at((xx - 1, k), (96, 174, 84))
                        if xx - 2 >= 0:
                            s.set_at((xx - 2, k), (70, 150, 70))
                    if k % 5 == 1 and xx + 2 < SM:
                        s.set_at((xx + 2, k), (120, 190, 96))
            end_x = x0 + int(round(math.sin((length - 1) * 0.4 + i) * 1.2 + sway * (length - 1) / 12.0))
            if v == 2 and 0 <= end_x < SM and i % 2 == 0:
                pygame.draw.rect(s, (232, 108, 170), (max(0, end_x - 1), length - 1, 2, 2))
    return pix(SM, 24, fn)


