def console_lesson(title, topic, theory, example, task, goal, hint, solution,
                   tests=None, commands=None, starter="", win="Верно!", **rules):
    d = {
        "kind": "console", "title": title, "topic": topic, "theory": theory,
        "example": example, "task": task, "goal_text": goal, "hint": hint,
        "solution": solution, "tests": tests if tests is not None else [],
        "commands": commands or [], "starter": starter, "win": win,
    }
    d.update(rules)
    return d


def grid_lesson(title, topic, theory, example, task, commands, hint, solution, start, sticks, goal,
                zombies=(), goal_zombies=0, max_lines=None, require_def=False, limit_hint=None,
                win="Верно!", starter=""):
    d = {
        "kind": "grid", "title": title, "topic": topic, "theory": theory, "example": example,
        "task": task, "commands": commands, "hint": hint, "solution": solution,
        "start": start, "sticks": list(sticks), "zombies": list(zombies), "goal": goal,
        "goal_zombies": goal_zombies, "max_lines": max_lines, "require_def": require_def,
        "win": win, "starter": starter,
    }
    if limit_hint:
        d["limit_hint"] = limit_hint
    return d


