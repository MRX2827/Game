def make_banana(v, frame):
    pal = GREENS[1 + v % 2]
    sw = (-1, 1)[frame]

    def fn(s):
        b = (10, 18)
        for (dx, dy) in ((-7, -9), (7, -9), (0, -13), (-9, -3), (9, -3)):
            t = (b[0] + dx + (sw if dy < -8 else 0), b[1] + dy)
            m = ((b[0] + t[0]) / 2.0, (b[1] + t[1]) / 2.0)
            ln = math.hypot(t[0] - b[0], t[1] - b[1]) or 1.0
            nx, ny = -(t[1] - b[1]) / ln * 3, (t[0] - b[0]) / ln * 3
            pts = [b, (int(m[0] + nx), int(m[1] + ny)), t, (int(m[0] - nx), int(m[1] - ny))]
            pygame.draw.polygon(s, pal[1], pts)
            pygame.draw.line(s, pal[2], b, t)
            s.set_at(t, pal[0])
    return pix(SM, SM, fn)


