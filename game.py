def groan(seed):
    dur = 1.1 + 0.25 * (seed % 4)
    n = _n(dur)
    t = np.arange(n) / SR
    f = 78 * (1 + 0.18 * (seed % 5)) * (1.0 + 0.25 * np.exp(-t / 0.4)) * (1.0 - 0.18 * t / dur)
    f = f * (1.0 + 0.03 * np.sin(2 * np.pi * 5.5 * t))
    ph = 2 * np.pi * np.cumsum(f) / SR
    x = sum((1.0 / (k ** 0.9)) * np.sin(ph * k) for k in range(1, 9))
    x = _band(x, None, 1100)
    breath = _band(_white(dur, seed + 200), 300, 1600) * 0.35
    env = np.sin(np.pi * t / dur) ** 0.7
    return _norm((x + breath) * env * (0.7 + 0.3 * np.sin(2 * np.pi * 3.2 * t + seed)), 0.65)


def snarl():
    n = _n(0.5)
