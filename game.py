class World:
    def __init__(self, level):
        self.x, self.y = level["start"]
        self.sticks = set(level["sticks"])
        self.zombies = set(level.get("zombies", []))
        self.taken = 0
        self.kills = 0

    def snapshot(self):
        return (self.x, self.y, frozenset(self.sticks), self.taken,
                frozenset(self.zombies), self.kills)


