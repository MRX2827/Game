def wind_loop(lo, hi, dur=6.0, seed=5, depth=0.7):
    x = _band(_white(dur, seed), lo, hi)
    m = _band(_white(dur, seed + 1), None, 0.5)
    m = (m - m.min()) / (m.max() - m.min() + 1e-9)
    return _norm(x * ((1 - depth) + depth * m), 0.6)


def rain_loop(dur=4.0, seed=8):
    n = _n(dur)
    hiss = _band(_white(dur, seed), 1800, 9500)
    patter = _band(_white(dur, seed + 1), 350, 1800) * 0.5
    rng = np.random.default_rng(seed + 2)
    drops = np.zeros(n)
    for _ in range(int(dur * 55)):
        i = int(rng.integers(0, n))
        tt = np.arange(120)
        seg = np.sin(2 * np.pi * rng.uniform(2200, 5200) * tt / SR) * np.exp(-tt / 18.0) * rng.uniform(0.1, 0.5)
        drops[(tt + i) % n] += seg
    return _norm(hiss * 0.55 + patter * 0.45 + drops * 0.5, 0.6)


def thunder(seed, near):
    dur = 3.2 if near else 4.5
    n = _n(dur)
    t = np.arange(n) / SR
    rumble = _norm(_band(_white(dur, seed), 25, 180 if near else 120), 1.0)
    env = (1 - np.exp(-t / 0.25)) * np.exp(-t / (1.0 if near else 1.6)) * (0.7 + 0.3 * np.sin(2 * np.pi * 1.3 * t + seed))
    crack = _norm(_band(_white(dur, seed + 1), 300, 4000), 1.0) * np.exp(-t / 0.06) * (1.0 if near else 0.0)
    return _norm(rumble * env + crack * 0.35, 0.85)


def water_loop(dur=5.0, seed=11):
    n = _n(dur)
    t = np.arange(n) / SR
    flow = _band(_white(dur, seed), 150, 1400)
    lap = 0.55 + 0.45 * np.sin(2 * np.pi * (2 / dur) * t) * np.sin(2 * np.pi * (3 / dur) * t + 1)
    sparkle = _band(_white(dur, seed + 1), 2000, 6000) * 0.12 * (0.5 + 0.5 * np.sin(2 * np.pi * (7 / dur) * t))
    rng = np.random.default_rng(seed + 2)
    bubbles = np.zeros(n)
    for _ in range(int(dur * 5)):
        i = int(rng.integers(0, n))
        seg = _sweep(350, 900, 0.04, (1.0,)) * np.sin(np.pi * np.linspace(0, 1, _n(0.04))) * rng.uniform(0.1, 0.3)
        bubbles[(np.arange(len(seg)) + i) % n] += seg
    return _norm(flow * lap * 0.7 + sparkle + bubbles, 0.5)


