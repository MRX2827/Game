    t = np.arange(n) / SR
    thud = np.sin(2 * np.pi * (65 + seed * 5) * t) * np.exp(-t / 0.06)
    drag = _band(_white(0.3, seed + 120), 250, 1400) * _env(n, 0.05, 0.08) * 0.5
    x = _band(thud * 0.9 + drag, None, 350 if far else 1400)
    return _norm(x, 0.5)


