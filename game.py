def fire_loop(dur=4.0, seed=3):
    n = _n(dur)
    rng = np.random.default_rng(seed)
    base = _band(_white(dur, seed), 60, 320) * 0.5 + _band(_white(dur, seed + 1), 500, 4000) * 0.06
    pops = np.zeros(n)
    for _ in range(int(dur * 22)):
        i = int(rng.integers(0, n))
        length = int(rng.integers(30, 260))
        seg = rng.standard_normal(length) * np.exp(-np.arange(length) / (length / 4.0)) * rng.uniform(0.15, 1.0) ** 2
        pops[(np.arange(length) + i) % n] += seg
    pops = _band(pops, 700, 7000)
    flick = 0.75 + 0.25 * np.sin(2 * np.pi * np.arange(n) / SR * (3.0 / dur))
    return _norm((base + pops * 1.4) * flick, 0.7)


