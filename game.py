def _n(dur):
    return int(SR * dur)


def _white(dur, seed=0):
    return np.random.default_rng(seed).standard_normal(_n(dur))


def _band(x, lo=None, hi=None):
    """Полосовой фильтр через FFT (петли получаются бесшовными)."""
    n = len(x)
    spec = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1.0 / SR)
    m = np.ones_like(f)
    if lo:
        m = m / (1.0 + (lo / np.maximum(f, 1e-3)) ** 4)
    if hi:
        m = m / (1.0 + (f / hi) ** 4)
    return np.fft.irfft(spec * m, n)


def _norm(x, peak=0.8):
    m = float(np.max(np.abs(x)))
    return x / m * peak if m > 1e-9 else x


def _env(n, attack, decay):
    t = np.arange(n) / SR
    return np.minimum(1.0, t / max(attack, 1e-4)) * np.exp(-t / max(decay, 1e-4))


def _tone(freq, dur, harm=(1.0,)):
    t = np.arange(_n(dur)) / SR
    return sum(h * np.sin(2 * np.pi * freq * (i + 1) * t) for i, h in enumerate(harm))


def _sweep(f0, f1, dur, harm=(1.0, 0.2)):
    n = _n(dur)
    ph = 2 * np.pi * np.cumsum(np.linspace(f0, f1, n)) / SR
    return sum(h * np.sin(ph * (i + 1)) for i, h in enumerate(harm))


def _mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[:len(p)] += p
    return out


def _echo(x, delay, gain):
    out = np.zeros(len(x) + _n(delay))
    out[:len(x)] += x
    out[_n(delay):_n(delay) + len(x)] += x * gain
    return out


